function slugify(title) {
  return title
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 64);
}

const seen = new Set();
const games = [];
for (const title of [...fromAula5, ...extra]) {
  const id = slugify(title);
  if (!id || seen.has(id)) continue;
  seen.add(id);
  games.push({
    id,
    title,
    rating: null,
    blurb: null,
    cover: null,
    descriptors: [],
    source: fromAula5.includes(title) ? 'aula5-v1' : 'stub',
  });
}

